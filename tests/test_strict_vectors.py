"""The shared strict cases load: valid JSON, every case complete, names unique.

``associate/contract/strict_vectors.json`` is generated by
``scripts/strict_vectors.ts`` from the extension's own code and is held
byte-identical in evidence-cli, whose strict re-check runs the cases. This
repository only checks that the file is well formed; the re-check is not here.
The shape is described in ``docs/notes/strict-vectors.md``.
"""

from __future__ import annotations

import json

from associate.contract import contract_dir

INPUT_KEYS = {
    "checkout_root",
    "walk",
    "results",
    "prior_runs",
    "children",
    "finish",
    "contract",
    "decider",
    "returned_before",
    "rounds_left",
}
CONTRACT_KEYS = {"strict", "support_passes", "min_quote_length", "retry_rounds", "source_kinds"}
EXPECT_KEYS = {
    "facts",
    "graph",
    "verdicts",
    "open_items",
    "counts",
    "drop_reasons",
    "judge_counts",
    "report",
}
FACT_KEYS = {
    "id",
    "kind_stated",
    "kind_checked",
    "worded",
    "status",
    "strict_outcome",
    "drop_reason",
    "dropped_by",
    "evidence",
    "judge",
    "sent",
}
EVIDENCE_KEYS = {"quote", "command", "command_from", "result_file", "lines", "run"}
ITEM_KEYS = {"id", "outcome", "reason", "strict_outcome", "strict_reason"}


def _doc() -> dict:
    return json.loads((contract_dir() / "strict_vectors.json").read_text(encoding="utf-8"))


def test_the_file_is_json_with_a_version_redaction_and_cases():
    doc = _doc()
    assert doc["version"] == 1
    assert isinstance(doc["redaction"]["replacement"], str)
    assert all(isinstance(p, str) for p in doc["redaction"]["patterns"])
    assert isinstance(doc["cases"], list) and doc["cases"]


def test_every_case_has_the_required_keys():
    for case in _doc()["cases"]:
        name = case.get("name")
        assert isinstance(name, str) and name, case
        assert isinstance(case.get("note"), str) and case["note"], name
        assert INPUT_KEYS <= set(case["input"]), (name, INPUT_KEYS - set(case["input"]))
        assert CONTRACT_KEYS <= set(case["input"]["contract"]), name
        assert EXPECT_KEYS <= set(case["expect"]), (name, EXPECT_KEYS - set(case["expect"]))
        assert set(case["expect"]["graph"]) == {"order", "refusals"}, name
        for fact in case["expect"]["facts"]:
            assert FACT_KEYS <= set(fact), (name, FACT_KEYS - set(fact))
            if fact["evidence"] is not None:
                assert EVIDENCE_KEYS <= set(fact["evidence"]), (name, fact["id"])
        for item in case["expect"]["verdicts"] + case["expect"]["open_items"]:
            assert ITEM_KEYS <= set(item), (name, item)


def test_case_names_are_unique():
    names = [case["name"] for case in _doc()["cases"]]
    assert len(names) == len(set(names))


def test_the_only_home_path_is_the_deliberate_one_in_the_command_case():
    """No tracked file names a home path; the one exception is test input for the ~ masking."""
    doc = _doc()
    for case in doc["cases"]:
        text = json.dumps(case)
        count = text.count("/home/") + text.count("/Users/") + text.count('"/root')
        if case["name"] == "command_relative_and_redacted":
            assert count == 1, count
            assert "deliberate test input" in case["note"]
        else:
            assert count == 0, case["name"]
        assert not case["input"]["checkout_root"].startswith(("/home/", "/Users/", "/root"))
